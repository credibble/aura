#!/usr/bin/env node
/**
 * Turns the Hairline sources in `app/hairline/` into ES modules the app can
 * import, under `src/components/hairline/`:
 *
 *   hairline/kernel.js     → src/components/hairline/kernel.js   (+ `export { HL }`)
 *   hairline/<name>.js     → src/components/hairline/figures/<name>.js (+ .d.ts)
 *
 * The sources stay in the exact format the `hairline-create` skill writes and
 * checks (a classic figure reading the global `HL` and ending in a
 * `hairline({ … })` call), so `look.mjs` / `validate.mjs` keep working on them
 * unchanged. The kernel is copied byte for byte; only an export line is added.
 *
 *   node scripts/sync-hairline.mjs           write the modules
 *   node scripts/sync-hairline.mjs --check   exit 1 if any module is stale (CI)
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "hairline");
const out = join(root, "src", "components", "hairline");
const check = process.argv.includes("--check");

const HEADER = "// GENERATED by scripts/sync-hairline.mjs from app/hairline/ — do not edit.\n";
const files = new Map();

const kernel = readFileSync(join(src, "kernel.js"), "utf8");
files.set(
  join(out, "kernel.js"),
  `${HEADER}/* eslint-disable */\n${kernel.trimEnd()}\nexport { HL };\n`,
);

for (const f of readdirSync(src)
  .filter((n) => n.endsWith(".js") && n !== "kernel.js")
  .sort()) {
  const code = readFileSync(join(src, f), "utf8").trimEnd();
  // The declaration is the file's last statement: `hairline({ … });`
  const at = code.lastIndexOf("\nhairline(");
  if (at < 0) throw new Error(`${f}: no trailing hairline({ … }) declaration`);
  const name = f.replace(/\.js$/, "");
  files.set(
    join(out, "figures", f),
    `${HEADER}/* eslint-disable */\nimport { HL } from "../kernel.js";\nconst hairline = (figure) => figure;\n` +
      `${code.slice(0, at)}\nexport default ${code.slice(at + 1)}\n`,
  );
  files.set(
    join(out, "figures", `${name}.d.ts`),
    `${HEADER}import type { HairlineFigureSpec } from "../types";\ndeclare const figure: HairlineFigureSpec;\nexport default figure;\n`,
  );
}

let stale = 0;
for (const [path, text] of files) {
  const now = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (now === text) continue;
  stale++;
  if (check) {
    console.error(`stale: ${path}`);
    continue;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  console.log(`wrote ${path}`);
}
if (check && stale) {
  console.error(`${stale} Hairline module(s) out of date — run node scripts/sync-hairline.mjs`);
  process.exit(1);
}
if (!stale) console.log("Hairline modules up to date.");
